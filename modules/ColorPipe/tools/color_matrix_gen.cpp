#include "ColorSpaces.hpp"
#include <cstdint>
#include <filesystem>
#include <format>
#include <fstream>
#include <iostream>
#include <iterator>
#include <print>
#include <string>
#include <string_view>

// a Slang matrix multiplies a row vector, so each constant is the transpose of the color_math matrix. The file is
// rewritten only when its contents change, so that an unchanged run does not re-run the cook

namespace
{
    [[nodiscard]] std::string FormatScalar(double value);
    [[nodiscard]] std::string FormatMatrix(std::string_view name, const color::Mat3d& column_vector_matrix);
    [[nodiscard]] std::string FormatWeights(std::string_view name, const color::Vec3d& weights);
    [[nodiscard]] std::string BuildSlangText();
    [[nodiscard]] bool FileHasContents(const std::filesystem::path& path, const std::string& text);
}

int main(int argc, char** argv)
{
    if (argc != 2)
    {
        std::println(stderr, "usage: color_matrix_gen <path of ddColorGenerated.slang>");
        return 1;
    }

    const std::filesystem::path outputPath{ argv[1] };
    const std::string text = BuildSlangText();

    if (FileHasContents(outputPath, text))
    {
        std::println("=== {} is up to date ===", outputPath.string());
        return 0;
    }

    std::ofstream output(outputPath, std::ios::binary | std::ios::trunc);
    output << text;
    output.close();

    if (!output)
    {
        std::println(stderr, "color_matrix_gen: could not write {}", outputPath.string());
        return 1;
    }

    std::println("=== Wrote {} ===", outputPath.string());
    return 0;
}

namespace
{
    std::string FormatScalar(double value)
    {
        std::string text = std::format("{:.9g}", value);

        if (text.find_first_of(".en") == std::string::npos)
        {
            text += ".0";
        }

        return text;
    }

    std::string FormatMatrix(std::string_view name, const color::Mat3d& column_vector_matrix)
    {
        const color::Mat3d rowVectorMatrix = color::Transpose(column_vector_matrix);
        std::string text = std::format("public static const float3x3 {} = float3x3(\n", name);

        for (int32_t row = 0; row < 3; ++row)
        {
            const std::array<double, 3>& values = rowVectorMatrix.Rows[row];
            const std::string_view ending = row == 2 ? ");\n\n" : ",\n";
            text += std::format("    {}, {}, {}{}", FormatScalar(values[0]), FormatScalar(values[1]), FormatScalar(values[2]), ending);
        }

        return text;
    }

    std::string FormatWeights(std::string_view name, const color::Vec3d& weights)
    {
        return std::format("public static const float3 {} = float3({}, {}, {});\n\n", name,
            FormatScalar(weights.X), FormatScalar(weights.Y), FormatScalar(weights.Z));
    }

    std::string BuildSlangText()
    {
        using color::ChromaticAdaptation;

        const color::Mat3d ap1ToXyz = color::RgbToXyz(color::AP1);
        const color::Vec3d ap1Weights{ ap1ToXyz.Rows[1][0], ap1ToXyz.Rows[1][1], ap1ToXyz.Rows[1][2] };

        std::string text;
        text += "// Auto-generated by modules/ColorPipe/tools/color_matrix_gen.cpp -- do not edit\n";
        text += "// Each matrix multiplies a row vector: mul(rgb, matrix). It is the transpose of the column-vector matrix\n";
        text += "// that color::RgbToRgb returns. Conversions between gamuts use Bradford adaptation.\n";
        text += "implementing ddColor;\n\n";

        text += FormatMatrix("Rec709ToAp1Matrix", color::RgbToRgb(color::Rec709, color::AP1, ChromaticAdaptation::Bradford));
        text += FormatMatrix("Ap1ToRec709Matrix", color::RgbToRgb(color::AP1, color::Rec709, ChromaticAdaptation::Bradford));
        text += FormatMatrix("Rec2020ToAp1Matrix", color::RgbToRgb(color::Rec2020, color::AP1, ChromaticAdaptation::Bradford));
        text += FormatMatrix("Ap1ToRec2020Matrix", color::RgbToRgb(color::AP1, color::Rec2020, ChromaticAdaptation::Bradford));
        text += FormatMatrix("DisplayP3ToAp1Matrix", color::RgbToRgb(color::DisplayP3, color::AP1, ChromaticAdaptation::Bradford));
        text += FormatMatrix("Ap1ToDisplayP3Matrix", color::RgbToRgb(color::AP1, color::DisplayP3, ChromaticAdaptation::Bradford));
        text += FormatMatrix("XyzToAp1Matrix", color::XyzToRgb(color::AP1));
        text += FormatWeights("Ap1LuminanceWeights", ap1Weights);

        return text;
    }

    bool FileHasContents(const std::filesystem::path& path, const std::string& text)
    {
        std::ifstream input(path, std::ios::binary);

        if (!input)
        {
            return false;
        }

        const std::string existing{ std::istreambuf_iterator<char>(input), std::istreambuf_iterator<char>() };

        return existing == text;
    }
}
